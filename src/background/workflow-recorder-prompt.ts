/**
 * 构建录制结果的 AI 审计提示词。
 * 审计阶段生成完整 workflow JSON，由后台直接保存；用户可在后续对话中修改后再次保存。
 */
export const buildRecorderAuditPrompt = (
    cleanSteps: Array<Record<string, unknown>>,
    startUrl: string,
): string => [
    '你是一个工作流审计助手。以下是用户在浏览器中录制的一系列操作步骤：',
    '',
    JSON.stringify(cleanSteps, null, 2),
    '',
    `起始 URL: ${startUrl}`,
    '',
    '可用的 action 名称（必须从以下清单选取，清单外的 action 会在保存和执行时被拒绝）：',
    '- tab_navigate — 标签页导航（打开/关闭/切换页面，params.action: navigate/open/close）',
    '- page — 页面读取与验证（params.action: view/snapshot/skeleton/assert/repair）',
    '- cdp_dom — DOM/CSS 只读查询（params.action: query_selector/query_selector_all/get_text/get_html/get_outer_html/get_attributes/get_box_model/get_document/css_get_computed_style/css_get_matched_rules/css_get_stylesheets/css_get_stylesheet/wait_for）',
    '- extract_data — 结构化数据提取',
    '- screenshot — 页面截图',
    '',
    '请完成以下任务：',
    '1. 去除明显的噪声步骤（误点击、重复操作）',
    '2. 合并连续的输入动作',
    '3. 为每步添加中文说明（note 字段）',
    '4. 识别用户输入的变量部分，用 {{param_name}} 替代，并在 parameters 中定义',
    '5. 先根据录制步骤、起始 URL、页面语义和参数，生成可用的 name、label、description、triggers',
    '',
    '元数据规则：',
    '- 必须生成四个元数据字段：name、label、description、triggers。',
    '- name 使用稳定、简短的英文 snake_case 机器名，体现目标动作和对象，不得使用 workflow、未命名等泛化占位词。',
    '- label 是简洁中文显示名；description 是说明用户最终收益的一句话中文描述。',
    '- triggers 生成 2-5 个用户可能说的中文自然语言调用短语，覆盖同义表达，不要填工具名、action 名或选择器。',
    '- 如果任一元数据缺失、空白或不符合规则，先根据已有步骤自动推断并修正，再输出 JSON；只有录制内容确实无法判断目标时才询问用户补充。',
    '- 输出前自检 name、label、description、triggers、parameters、readable_steps、plan.steps 均存在且彼此一致。',
    '',
    '重要：',
    '- action 必须从上述清单中选取，不要使用 click/type/navigate 等原始录制动作名',
    '- 页面导航（URL 变化）使用 tab_navigate',
    '- 需要读取或验证页面时使用 page，并通过 params.action 选择具体动作',
    '- 需要查询 DOM/CSS 时使用 cdp_dom，且只能使用只读子动作；写入类子动作（set_text/set_html/storage_* 等）会被拒绝',
    '- plan 不支持点击、填写、按键或执行 JavaScript：录制中的点击/输入步骤不要改写成 cdp_input/cdp_frame，直接省略这些步骤，并说明用户需在页面上手动完成该操作',
    '- 审计完成后输出完整 workflow JSON；后台会自动调用 save_workflow 保存，不要等待用户二次确认或自行询问是否保存。',
    '- 用户后续提出修改时，更新同一份完整 workflow JSON；用户明确要求保存时直接调用 save_workflow。',
    '',
    '输出格式（严格 JSON，无多余文字）：',
    '{',
    '  "name": "search_products（英文下划线格式）",',
    '  "label": "显示名称（中文）",',
    '  "description": "一句话工作流描述（中文）",',
    '  "triggers": ["调用关键词或短语"],',
    '  "url_patterns": ["匹配的 URL 模式"],',
    '  "parameters": { "type": "object", "properties": {} },',
    '  "readable_steps": "人类可读的步骤描述（Markdown 编号列表，含参数标注）",',
    '  "plan": {',
    '    "steps": [',
    '      { "action": "tab_navigate", "params": { "action": "open", "url": "..." }, "note": "打开目标页" },',
    '      { "action": "page", "params": { "action": "view" }, "note": "读取页面内容" },',
    '      { "action": "cdp_dom", "params": { "action": "query_selector", "selector": "input" }, "note": "查询目标元素" }',
    '    ]',
    '  }',
    '}',
].join('\n');
